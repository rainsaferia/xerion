"""Deterministic PDF Schedule Report generation using ReportLab (PI-046).

Rules (01_PRD.md, 02_SYSTEM_ARCHITECTURE.md, 07_UI_UX_SPEC.md, 08_DEVELOPMENT_BACKLOG.md):
- Report references exact project version, project code, and data date.
- Includes overview, methodology, findings, limitations, and generation timestamp.
- Hexagonal domain isolation: zero web framework, adapter, or AI imports.
"""

import io
import uuid
from datetime import date, datetime
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


def build_schedule_analysis_pdf(
    project_name: str,
    project_code: str,
    project_version_id: uuid.UUID | str,
    data_date: date | str | None,
    generated_at: datetime,
    generated_by_email: str | None = None,
    metrics: dict[str, Any] | None = None,
    quality_summary: dict[str, Any] | None = None,
    milestone_forecasts: list[dict[str, Any]] | None = None,
    options: dict[str, Any] | None = None,
) -> bytes:
    """Generate a structured, professional EPC schedule analysis PDF in memory."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=40,
        rightMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#1A365D"),
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=11,
        leading=15,
        textColor=colors.HexColor("#4A5568"),
    )
    h2_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=17,
        textColor=colors.HexColor("#2B6CB0"),
        spaceBefore=14,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "StandardBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#2D3748"),
    )
    body_bold = ParagraphStyle(
        "StandardBodyBold",
        parent=body_style,
        fontName="Helvetica-Bold",
    )
    meta_label = ParagraphStyle(
        "MetaLabel",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#718096"),
    )
    meta_val = ParagraphStyle(
        "MetaVal",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#1A202C"),
    )
    disclaimer_style = ParagraphStyle(
        "DisclaimerText",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#718096"),
    )

    story: list[Any] = []

    # Title & Header
    story.append(Paragraph("Schedule Analysis Report", title_style))
    story.append(Paragraph(f"Project: {project_name} ({project_code})", subtitle_style))
    story.append(Spacer(1, 10))

    # Provenance & Metadata Box
    data_date_str = str(data_date) if data_date else "Not specified"
    generated_str = generated_at.strftime("%Y-%m-%d %H:%M:%S UTC")
    author_str = generated_by_email or "Platform System"
    version_str = str(project_version_id)

    meta_data = [
        [
            Paragraph("DATA DATE:", meta_label),
            Paragraph(data_date_str, meta_val),
            Paragraph("GENERATED AT:", meta_label),
            Paragraph(generated_str, meta_val),
        ],
        [
            Paragraph("VERSION ID:", meta_label),
            Paragraph(version_str, meta_val),
            Paragraph("GENERATED BY:", meta_label),
            Paragraph(author_str, meta_val),
        ],
        [
            Paragraph("REPORT TYPE:", meta_label),
            Paragraph("Deterministic Schedule Analysis (P0)", meta_val),
            Paragraph("CLASSIFICATION:", meta_label),
            Paragraph("Confidential / Project Controls", meta_val),
        ],
    ]
    meta_table = Table(meta_data, colWidths=[90, 176, 100, 166])
    meta_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F7FAFC")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#EDF2F7")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(meta_table)
    story.append(Spacer(1, 12))

    # Section 1: Executive Overview
    story.append(Paragraph("1. Executive Schedule Overview", h2_style))
    story.append(
        HRFlowable(
            width="100%", thickness=1, color=colors.HexColor("#CBD5E0"), spaceBefore=2, spaceAfter=8
        )
    )

    m = metrics or {}
    total_acts = m.get("total_activities", "N/A")
    not_started = m.get("not_started_count", "N/A")
    in_progress = m.get("in_progress_count", "N/A")
    completed = m.get("completed_count", "N/A")
    critical = m.get("critical_count", "N/A")
    plan_start = m.get("planned_start") or "N/A"
    plan_finish = m.get("planned_finish") or "N/A"

    overview_rows = [
        [
            Paragraph("Metric", body_bold),
            Paragraph("Value", body_bold),
            Paragraph("Metric", body_bold),
            Paragraph("Value", body_bold),
        ],
        [
            Paragraph("Total Activities", body_style),
            Paragraph(str(total_acts), body_style),
            Paragraph("Critical Activities", body_style),
            Paragraph(str(critical), body_style),
        ],
        [
            Paragraph("Not Started", body_style),
            Paragraph(str(not_started), body_style),
            Paragraph("In Progress", body_style),
            Paragraph(str(in_progress), body_style),
        ],
        [
            Paragraph("Completed", body_style),
            Paragraph(str(completed), body_style),
            Paragraph("Schedule Span", body_style),
            Paragraph(f"{plan_start} to {plan_finish}", body_style),
        ],
    ]
    overview_table = Table(overview_rows, colWidths=[133, 133, 133, 133])
    overview_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EDF2F7")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E0")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    story.append(overview_table)
    story.append(Spacer(1, 10))

    # Section 2: Schedule Quality Findings
    story.append(Paragraph("2. Schedule Quality & Integrity Checks", h2_style))
    story.append(
        HRFlowable(
            width="100%", thickness=1, color=colors.HexColor("#CBD5E0"), spaceBefore=2, spaceAfter=8
        )
    )

    q = quality_summary or {}
    findings = q.get("findings", [])
    passed_cnt = q.get("passed_checks", 0)
    warn_cnt = q.get("warning_checks", 0)
    err_cnt = q.get("error_checks", 0)

    quality_summary_text = (
        f"Automated quality evaluation results: <b>{passed_cnt} passed</b>, "
        f"<b>{warn_cnt} warnings</b>, and <b>{err_cnt} errors</b> detected."
    )
    story.append(Paragraph(quality_summary_text, body_style))
    story.append(Spacer(1, 6))

    if findings:
        finding_rows = [
            [
                Paragraph("Category", body_bold),
                Paragraph("Severity", body_bold),
                Paragraph("Rule ID", body_bold),
                Paragraph("Description", body_bold),
            ]
        ]
        for f in findings[:10]:  # Limit top 10 findings for PDF summary
            finding_rows.append(
                [
                    Paragraph(str(f.get("category", "")), body_style),
                    Paragraph(str(f.get("severity", "")).upper(), body_style),
                    Paragraph(str(f.get("rule_id", "")), body_style),
                    Paragraph(str(f.get("description", "")), body_style),
                ]
            )
        finding_table = Table(finding_rows, colWidths=[100, 70, 110, 252])
        finding_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EDF2F7")),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E0")),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )
        story.append(finding_table)
    else:
        story.append(Paragraph("No open schedule quality warnings or errors found.", body_style))

    story.append(Spacer(1, 10))

    # Section 3: Milestone Schedule & Forecasts
    story.append(Paragraph("3. Key Milestone Schedule & Projections", h2_style))
    story.append(
        HRFlowable(
            width="100%", thickness=1, color=colors.HexColor("#CBD5E0"), spaceBefore=2, spaceAfter=8
        )
    )

    mf_list = milestone_forecasts or []
    if mf_list:
        ms_rows = [
            [
                Paragraph("Milestone Code", body_bold),
                Paragraph("Milestone Name", body_bold),
                Paragraph("Source Finish", body_bold),
                Paragraph("Forecast Finish", body_bold),
                Paragraph("Variance (d)", body_bold),
            ]
        ]
        for item in mf_list[:15]:
            var_d = item.get("variance_days", 0)
            if isinstance(var_d, int | float):
                var_text = f"{int(var_d):+d}" if float(var_d).is_integer() else f"{var_d:+.1f}"
            else:
                var_text = str(var_d)
            ms_rows.append(
                [
                    Paragraph(str(item.get("activity_code", "")), body_style),
                    Paragraph(str(item.get("activity_name", "")), body_style),
                    Paragraph(str(item.get("source_finish_date") or "N/A"), body_style),
                    Paragraph(str(item.get("forecast_finish_date") or "N/A"), body_style),
                    Paragraph(var_text, body_style),
                ]
            )
        ms_table = Table(ms_rows, colWidths=[90, 192, 85, 85, 80])
        ms_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EDF2F7")),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E0")),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )
        story.append(ms_table)
    else:
        story.append(Paragraph("No milestone activities identified in this version.", body_style))

    story.append(Spacer(1, 14))

    # Section 4: Methodology Notes & Limitations (Keep together)
    notes_block: list[Any] = [
        Paragraph("4. Methodology Notes & Analysis Limitations", h2_style),
        HRFlowable(
            width="100%",
            thickness=1,
            color=colors.HexColor("#CBD5E0"),
            spaceBefore=2,
            spaceAfter=8,
        ),
        Paragraph(
            "<b>Deterministic Schedule Engine:</b> Calculations reflect pure Critical Path Method "
            "(CPM) logic and imported source floats without stochastic perturbation. Float "
            "absorption analysis evaluates Finish-to-Start predecessor/successor links within "
            "the selected schedule version.",
            body_style,
        ),
        Spacer(1, 4),
        Paragraph(
            "<b>Zero-Mutation Assurance:</b> Schedule data is immutable. Analysis runs and report "
            "exports do not modify baseline or imported schedule records.",
            body_style,
        ),
        Spacer(1, 4),
        Paragraph(
            "<b>Caveats & Disclaimers:</b> Forecast dates reflect imported project constraints and "
            "deterministic logic. They do not constitute a probabilistic risk assessment "
            "(Monte Carlo) or contractual extension-of-time entitlement. Calendar shift "
            "exceptions and complex lag behaviors must be validated against original agreements.",
            disclaimer_style,
        ),
    ]
    story.append(KeepTogether(notes_block))

    # Build PDF into buffer
    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()
